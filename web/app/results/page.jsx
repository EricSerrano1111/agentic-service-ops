import Bar from "../components/Bar";
import results from "../../data/results.json";

// The evaluation results page (ADR-117 item 4; data dictionary section 6, rule 11). Every figure
// is read from web/data/results.json, which scripts/build_results_data.py generates from the
// committed result files. Nothing is typed in here, and nothing is computed except bar widths.

export const metadata = {
  title: "Evaluation results · Service Ops Intelligence",
  description: "The evaluation's headline figures, each traced to the file it was read from.",
};

const F = results.figures;
const REPORT_URL = `https://github.com/EricSerrano1111/agentic-service-ops/blob/main/${results.report}`;

// Rule 11's caveats, word for word. Backticks mark code.
const CAVEATS = [
  "All data in this system is synthetic.",
  "The evaluation sets were generated by a model of the same family as the system; 10 golden items are owner-written.",
  "QA's catch rate is an upper bound: its author drafted the faults.",
  "`route_v6`'s comparison was made after the results, on sets already used.",
  "These figures describe the evaluated Sprint 5 system unless marked otherwise.",
];

function inline(text) {
  return text.split("`").map((part, i) => (i % 2 ? <code key={i}>{part}</code> : part));
}

function Stat({ id, label }) {
  const f = F[id];
  return (
    <div className="stat">
      <dt>{label ?? f.label}</dt>
      <dd>
        <strong>{f.text}</strong>
        <code className="src">{f.source}</code>
      </dd>
    </div>
  );
}

function Card({ title, headline, children }) {
  return (
    <section className="card card-pad stat-card">
      <h3>{title}</h3>
      <p className="stat-headline">{F[headline].text}</p>
      <code className="src">{F[headline].source}</code>
      <dl className="stats">{children}</dl>
    </section>
  );
}

function fraction(id) {
  return { value: F[id].number, max: F[id].of };
}

export default function Results() {
  return (
    <main id="main" className="prose results">
      <h1>Evaluation results</h1>
      <p className="lede">
        The headline figures of the evaluation. Each one is read from the result file named under
        it, and checked against the evaluation report on every build.
      </p>

      <section>
        <h2>Summary</h2>
        <div className="stat-grid">
          <Card title="Routing, held-out" headline="routing_heldout_run1">
            <Stat id="routing_heldout_run2" label="Run 2" />
            <Stat id="routing_heldout_run3" label="Run 3" />
            <Stat id="routing_heldout_without_ambiguous" />
            <Stat id="routing_heldout_ambiguous_not_flagged" />
            <Stat id="routing_heldout_out_of_scope_accepted" />
          </Card>
          <Card title="Golden set" headline="golden_mechanical">
            <Stat id="golden_owner" />
          </Card>
          <Card title="QA fault catch rate" headline="qa_faults_m1">
            <Stat id="qa_faults_m1_rate" />
            <Stat id="qa_faults_m2" />
          </Card>
          <Card title="Sentiment, macro-F1" headline="sentiment_bert">
            <Stat id="sentiment_tfidf" />
          </Card>
          <Card title="Forecast, holdout error" headline="forecast_holdout_volume_v2">
            <Stat id="forecast_holdout_seasonal_naive" />
            <Stat id="forecast_served" />
          </Card>
          <Card title="Production-grade" headline="production_grade" />
        </div>
      </section>

      <section>
        <h2>Comparisons</h2>
        <div className="card card-pad bars">
          <h3>Sentiment: macro-F1, higher is better</h3>
          <Bar label="BERT" text={F.sentiment_bert.text} value={F.sentiment_bert.number} max={1} source={F.sentiment_bert.source} />
          <Bar label="TF-IDF" text={F.sentiment_tfidf.text} value={F.sentiment_tfidf.number} max={1} source={F.sentiment_tfidf.source} base />
        </div>
        <div className="card card-pad bars">
          <h3>Forecast: holdout MAPE, lower is better</h3>
          <Bar label="volume_v2" text={F.forecast_holdout_volume_v2.text} value={F.forecast_holdout_volume_v2.number} max={F.forecast_holdout_seasonal_naive.number} source={F.forecast_holdout_volume_v2.source} />
          <Bar label="Seasonal naive" text={F.forecast_holdout_seasonal_naive.text} value={F.forecast_holdout_seasonal_naive.number} max={F.forecast_holdout_seasonal_naive.number} source={F.forecast_holdout_seasonal_naive.source} base />
        </div>
        <div className="card card-pad bars">
          <h3>Ambiguous questions recognised, higher is better</h3>
          <Bar label="route_v6" text={F.fr03_route_v6.text} {...fraction("fr03_route_v6")} source={F.fr03_route_v6.source} />
          <Bar label="route_v3" text={F.fr03_route_v3.text} {...fraction("fr03_route_v3")} source={F.fr03_route_v3.source} base />
        </div>
      </section>

      <section>
        <h2>FR-03: ambiguous questions</h2>
        <p>
          FR-03 asks the router to ask for a rephrase when a question is ambiguous. It is not met:{" "}
          <code>route_v6</code> recognised {F.fr03_route_v6.text} ambiguous questions against{" "}
          {F.fr03_route_v3.text} for <code>route_v3</code>, which is below the floor set for it, and
          the third attempt to improve it ended in a {F.fr03_third_attempt.text}.
        </p>
        <p>
          It is partly addressed because <code>route_v6</code> is now the default router, but about
          one ambiguous question in three is still routed to a best guess.
        </p>
        <p className="small muted">
          <code className="src">{F.fr03_route_v6.source}</code>
        </p>
      </section>

      <section>
        <h2>Cost</h2>
        <dl className="stats card card-pad">
          <Stat id="cost_heldout" label="Held-out routing and golden run, list price" />
          <Stat id="cost_heldout_requests" label="Requests in that run" />
          <Stat id="cost_gcp" />
        </dl>
      </section>

      <section>
        <h2>Caveats</h2>
        <ul className="plain-list caveats">
          {CAVEATS.map((c) => (
            <li key={c}>{inline(c)}</li>
          ))}
        </ul>
      </section>

      <section>
        <h2>The full report</h2>
        <p>
          <a href={REPORT_URL}>Read the full evaluation report</a> in the public repository.
        </p>
      </section>
    </main>
  );
}
