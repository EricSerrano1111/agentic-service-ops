"""Write evals/results/sprint5_failure_data.md from the two score files (Prompt X, section 3).

Data only, no interpretation beyond the pre-registered taxonomy. The disclosure lines are
copied from their sources, not retyped.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RES = ROOT / "evals" / "results"
ROUTING = json.loads((RES / "routing_heldout_v1" / "2026-10-13" / "score.json").read_text("utf-8"))
GOLDEN = json.loads((RES / "golden_v2" / "2026-10-13" / "score.json").read_text("utf-8"))
GOLDEN_ITEMS = {
    json.loads(x)["id"]: json.loads(x)
    for x in (ROOT / "evals" / "golden" / "golden_v2.jsonl").read_text("utf-8").splitlines()
    if x.strip()
}
REPORT = (ROOT / "docs" / "evaluation-report.md").read_text("utf-8")
ADR_094 = (
    "In a real deployment, evaluation sets would come from real user questions and subject-matter "
    "experts. Here they were generated by an independent model under a written brief; the owner "
    "reviewed the brief and spot-checked the ambiguous labels."
)


def persona_drop() -> str:
    m = re.search(r"\(1\) The owner's drops at the skim.*?(?= \(2\) `interp_fresh_v1`)", REPORT)
    if not m:
        raise SystemExit("persona-drop text not found in docs/evaluation-report.md (L-86)")
    return m.group(0)


def esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def main() -> int:
    out = ["# Sprint 5 failure-analysis data (Prompt X)", ""]
    out += [
        "Run date 2026-10-13; deployed images tagged `9607fa72` (tree equals `eval-freeze-s5`), "
        "paid mode (ADR-104). Data and the pre-registered taxonomy only; no interpretation here.",
        "",
        "**These sets are now spent for blind use** (`routing_heldout_v1` and `golden_v2` were run "
        "on 2026-10-13). Item text appears below and in the report; any later prompt change that "
        "reads this file must treat both sets as development data, not held-out data.",
        "",
        "## 1. Held-out routing: wrong item-runs",
        "",
        f"Per-run correct: {[r['correct'] for r in ROUTING['runs']]} of 50; "
        f"without the 7 ambiguous items: "
        f"{[r['correct_without_ambiguous'] for r in ROUTING['runs']]} of 43. "
        f"Flipping items: {ROUTING['flipping_items'] or 'none'}.",
        "",
        "Counts by taxonomy class (item-runs, 3 runs):",
        "",
        "| Class | Item-runs |",
        "|---|---|",
    ]
    out += [f"| {c} | {n} |" for c, n in ROUTING["taxonomy"].items()]
    out += [
        "",
        "| Pass | ID | Category | Expected | Got | Class | Outcome | Question |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for w in sorted(ROUTING["wrong_item_runs"], key=lambda w: (w["id"], w["pass"])):
        out.append(
            f"| {w['pass']} | {w['id']} | {w['category']} | {w['expected']} | {w['got']} | "
            f"{w['class']} | {w['outcome']} | {esc(w['question'])} |"
        )
    out += ["", "## 2. Golden run: failed items (mechanical score, golden_scoring.md)", ""]
    out += ["| ID | Components | What failed | Question |", "|---|---|---|---|"]
    for it in GOLDEN["items"]:
        if it["pass"]:
            continue
        comp = f"C1 {it['c1']}, C2 {it['c2']}, C3 {it['c3']}"
        out.append(
            f"| {it['id']} | {comp} | {esc('; '.join(it['why']))} | "
            f"{esc(GOLDEN_ITEMS[it['id']]['question'])} |"
        )
    out += [
        "",
        f"Golden: {GOLDEN['passed']}/{GOLDEN['n_scored']} pass the mechanical score. "
        "`must` and `must_not` are not part of it (owner review; see "
        "`evals/results/sprint5_x/golden_owner_review.csv`).",
        "",
        "## 3. Disclosures, verbatim",
        "",
        f'1. ADR-094\'s sentence: "{ADR_094}"',
        '2. "The sets were generated, not owner-written."',
        f"3. The persona-drop selection effect (L-86, update 2026-10-11): {persona_drop()}",
        "",
    ]
    (RES / "sprint5_failure_data.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote evals/results/sprint5_failure_data.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
